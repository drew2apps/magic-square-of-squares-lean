def selmer(basis_elems, places_imgs):
    g = len(basis_elems); cons = []
    for pl, img in places_imgs:
        d = pl.dim; M = [pl.vec(z) for z in basis_elems]; assert None not in M
        for phi in kd.nullspace(img, d):
            row = 0
            for k in range(g):
                if sum((phi >> t & 1) & M[k][t] for t in range(d)) & 1: row |= 1 << k
            cons.append(row)
    sol = kd.nullspace(cons, g)
    return sol

def edge(a, b, seed=1):
    rng = random.Random(seed)
    ap = gsc(-2, a); bp = gadd(gd.gmul(a, a), gsc(-4, b))
    primes = sorted(set([2]) | rat_primes(b) | rat_primes(bp))
    basis = [(0, 1), (1, 1)]
    for p in primes:
        if p == 2: continue
        if p % 4 == 3: basis.append((p, 0))
        else:
            g = gd.gprime(p); basis += [g, (g[0], -g[1])]
    PE, PEp = [], []
    for p in primes:
        for pl in kd.places_above(p):
            r = local_img(a, b, pl, rng)
            if r is None: return None
            PE.append((pl, r[0])); PEp.append((pl, r[1]))
    # Sel^phihat(E') uses alpha = x on E(K): local images on E.  Sel^phi(E) uses alpha' = X on E'.
    s_E = selmer(basis, PE); s_Ep = selmer(basis, PEp)
    return primes, basis, s_E, s_Ep

