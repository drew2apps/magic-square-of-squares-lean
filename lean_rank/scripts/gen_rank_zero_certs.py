#!/usr/bin/env python3
"""Generate LeanRank/RankZeroCensus.lean: rank-0 certificates for the census curves
w·f0·f8 of G1_FULL_SYSTEM.md, Result 3, model Y^2 = X(X + m^4)(X + n^4) (e2 = -m^4, e3 = -n^4).

Written by an AI model; not read by a person.  Untrusted generator: Lean re-checks everything
(Cert.check by decide +kernel, the tables, the factorizations, the witnesses).

usage: python3 -I gen_rank_zero_certs.py OUT.lean m,n [m,n ...]
Refuses (exit 1) a pair whose local test leaves more than 4 classes (rank > 0 or Sha[2] or a
test too weak), so the output only ever contains certificates that close.
"""
import itertools
import sys
from fractions import Fraction
from math import isqrt

MAXDEPTH = {2: 6, 3: 3}


def factor(N):
    N = abs(N); out = []; p = 2
    while p * p <= N:
        while N % p == 0:
            out.append(p); N //= p
        p += 1
    if N > 1:
        out.append(N)
    return out


def classes(S):
    out = []
    for k in range(len(S) + 1):
        for c in itertools.combinations(S, k):
            d = 1
            for p in c:
                d *= p
            out.append(d)
    return out + [-d for d in out]


def sqs(M):
    return sorted({r * r % M for r in range(M)})


def excluded_at(e2, e3, d1, d2, p, M):
    L = sqs(M)
    for s in L:
        for q in L:
            if (d1 * s) % p == 0 and q % p == 0:
                continue
            if not any((d1 * s - e2 * q - d2 * r) % M == 0 for r in L):
                continue
            if not any((d1 * d2 * (d1 * s - e3 * q) - r) % M == 0 for r in L):
                continue
            return False
    return True


def real_excluded(e2, e3, d1, d2):
    c = [(0, d1 > 0), (e2, d2 > 0), (e3, d1 * d2 > 0)]
    return any(u[1] and (not v[1]) and v[0] <= u[0] for u in c for v in c)


def sqfree(q):
    q = Fraction(q)
    z = q.numerator * q.denominator
    s = -1 if z < 0 else 1
    d = 1
    for p in set(factor(z)):
        if factor(z).count(p) % 2:
            d *= p
    return s * d


def sqrt_frac(q):
    q = Fraction(q)
    a, b = isqrt(q.numerator), isqrt(q.denominator)
    assert a * a == q.numerator and b * b == q.denominator
    return Fraction(a, b)


def lean_q(q):
    q = Fraction(q)
    return f"({q.numerator} / {q.denominator} : ℚ)" if q.denominator != 1 else f"({q.numerator} : ℚ)"


def cert(m, n):
    e2, e3 = -m ** 4, -n ** 4
    F1, F2 = factor(e2 * e3), factor(e2 * (e2 - e3))
    S1, S2 = sorted(set(F1)), sorted(set(F2))
    primes = sorted(set(S1) | set(S2))
    # candidate moduli, cheapest first (cost ~ (number of squares)^3)
    cands = sorted(((p, p ** k) for p in primes
                    for k in range(1, MAXDEPTH.get(p, 2) + 1)),
                   key=lambda t: len(sqs(t[1])) ** 3)
    good, used = [], {}
    for d1 in classes(S1):
        for d2 in classes(S2):
            if real_excluded(e2, e3, d1, d2):
                continue
            hit = None
            for (p, M) in cands:
                if excluded_at(e2, e3, d1, d2, p, M):
                    hit = (p, M); break
            if hit is None:
                good.append((d1, d2))
            else:
                used[hit] = used.get(hit, 0) + 1
    if len(good) > 4 or (1, 1) not in good:
        return None
    tabs = sorted(used, key=lambda t: len(sqs(t[1])) ** 3)
    # witnesses for the points of order 2
    def wit(v1, v2, v3):
        d1, d2 = sqfree(v1), sqfree(v2)
        assert (d1, d2) in good, (v1, v2, v3, d1, d2, good)
        w1, w2 = sqrt_frac(Fraction(v1) / d1), sqrt_frac(Fraction(v2) / d2)
        w3 = sqrt_frac(Fraction(v3) / (d1 * d2))
        return (d1, d2), (w1, w2, w3)
    tors = [wit(e2 * e3, -e2, -e3), wit(e2, e2 * (e2 - e3), e2 - e3),
            wit(e3, e3 - e2, e3 * (e3 - e2))]
    return dict(m=m, n=n, e2=e2, e3=e3, F1=F1, F2=F2, S1=S1, S2=S2, good=good, tabs=tabs,
                tors=tors, used=used)


HEAD = """import LeanRank.RankZeroGenCurve

/-!
# Rank-0 certificates for census curves `w·f0·f8` (generated)

Written by an AI model; not read by a person.  Generated by `scripts/gen_rank_zero_certs.py`
(untrusted); every certificate is re-checked by Lean (`Cert.check` by `decide +kernel`).

For the census pair `(m, n)` the curve `w·f0·f8 : y² = w(m² + n²w)(n² + m²w)` of
`G1_FULL_SYSTEM.md`, Result 3, is, with `X = m²n²w`, `Y = m²n²y`, the curve
`Y² = X(X + m⁴)(X + n⁴) = curve (−m⁴) (−n⁴)`.
-/

open WeierstrassCurve WeierstrassCurve.Affine
open LeanRank.RankZeroGen

namespace LeanRank.RankZeroCensus

"""


def emit(certs):
    out = [HEAD]
    mods = sorted({M for c in certs for (p, M) in c['tabs']})
    for M in mods:
        out.append(f"/-- The squares modulo `{M}`. -/\ndef sq{M} : List ℤ := {sqs(M)}\n\n")
    for c in certs:
        tag = f"{c['m']}_{c['n']}"
        tables = ", ".join(f"({p}, {M}, sq{M})" for (p, M) in c['tabs'])
        good = ", ".join(f"({a}, {b})" for a, b in c['good'])
        out.append(f"/-! ### `({c['m']}, {c['n']})`: `Y² = X(X + {-c['e2']})(X + {-c['e3']})` -/\n\n")
        out.append(f"def c_{tag} : Cert where\n  e₂ := {c['e2']}\n  e₃ := {c['e3']}\n"
                   f"  S₁ := {c['S1']}\n  S₂ := {c['S2']}\n  good := [{good}]\n"
                   f"  tables := [{tables}]\n\n")
        out.append(f"theorem c_{tag}_check : c_{tag}.check = true := by decide +kernel\n\n")
        lines = [f"theorem c_{tag}_tables : c_{tag}.TablesOK := by",
                 "  intro T hT",
                 f"  simp only [c_{tag}, List.mem_cons, List.not_mem_nil, or_false] at hT",
                 "  rcases hT with " + " | ".join(["rfl"] * len(c['tabs']))]
        for (p, M) in c['tabs']:
            lines.append(f"  · exact ⟨by simpa using int_prime {p} (by norm_num), by norm_num, by norm_num,"
                         f" by decide +kernel⟩")
        out.append("\n".join(lines) + "\n\n")
        def witness(t):
            (d1, d2), (w1, w2, w3) = t
            ws = ", ".join(lean_q(w) for w in (w1, w2, w3))
            return (f"⟨({d1}, {d2}), by decide, {ws}, by norm_num, by norm_num, by norm_num,\n"
                    f"      by norm_num [c_{tag}], by norm_num [c_{tag}], by norm_num [c_{tag}]⟩")
        out.append(
            f"/-- **`rank = 0`** for `Y² = X(X + {-c['e2']})(X + {-c['e3']})` (census pair "
            f"`({c['m']}, {c['n']})`, curve `w·f0·f8`). -/\n"
            f"theorem finrank_{tag} : Module.finrank ℤ (curve ({c['e2']}) ({c['e3']})).Point = 0 :=\n"
            f"  finrank_eq_zero_of c_{tag} (by decide) (by decide) (by decide)\n"
            f"    (by norm_num [c_{tag}]) (by norm_num [c_{tag}])\n"
            f"    (cover_of_factor (F := {c['F1']}) (by norm_num) (by decide) (by decide))\n"
            f"    (cover_of_factor (F := {c['F2']}) (by norm_num) (by decide) (by decide))\n"
            f"    c_{tag}_check c_{tag}_tables (by decide) (by decide)\n"
            f"    {witness(c['tors'][0])}\n"
            f"    {witness(c['tors'][1])}\n"
            f"    {witness(c['tors'][2])}\n\n")
    out.append("end LeanRank.RankZeroCensus\n\n")
    for c in certs:
        out.append(f"#print axioms LeanRank.RankZeroCensus.finrank_{c['m']}_{c['n']}\n")
    return "".join(out)


def main():
    path = sys.argv[1]
    certs = []
    for arg in sys.argv[2:]:
        m, n = map(int, arg.split(","))
        c = cert(m, n)
        if c is None:
            print(f"({m},{n}): REFUSED (more than 4 classes survive)", file=sys.stderr)
            return 1
        print(f"({m},{n}): good {c['good']}, exclusions {c['used']}", file=sys.stderr)
        certs.append(c)
    open(path, "w").write(emit(certs))
    return 0


if __name__ == "__main__":
    sys.exit(main())
