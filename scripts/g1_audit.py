#!/usr/bin/env python3
"""Independent audit of the G1 closures in Kepler71/magic-square-of-squares.

For coprime 1 <= n < m <= 20 (127 pairs) the diagonal cells of the G1 family are
    F0 = m^2 + n^2 t^2,  F4 = (m^2 + n^2)(t^2 + 1)/2,  F8 = n^2 + m^2 t^2.
With t = U/V in lowest terms, a full square needs the integers
    A = m^2 V^2 + n^2 U^2,  B = 2 (m^2 + n^2)(U^2 + V^2),  C = n^2 V^2 + m^2 U^2
to be squares. A modulus M obstructs the pair if no (U, V) mod M with gcd(U, V, M) = 1 makes
A, B, C all squares mod M.

usage: g1_audit.py [--lean PATH]     write the Lean certificate list to PATH
Ranks of E_B: Y^2 = X (X - (m^2-n^2)^2)(X - (m^2+n^2)^2) are recomputed with PARI if the
python package cypari2 is installed.
"""
import json, math, sys
from collections import Counter

MODULI = [7, 8, 16, 23, 25, 32, 47]


def obstructed(m, n, M):
    sq = {x * x % M for x in range(M)}
    for U in range(M):
        for V in range(M):
            if math.gcd(math.gcd(U, V), M) != 1:
                continue
            if ((m*m*V*V + n*n*U*U) % M in sq and (2*(m*m + n*n)*(U*U + V*V)) % M in sq
                    and (n*n*V*V + m*m*U*U) % M in sq):
                return False
    return True


pairs = [(m, n) for m in range(2, 21) for n in range(1, m) if math.gcd(m, n) == 1]
rows = []
for (m, n) in pairs:
    rows.append(dict(m=m, n=n, obstructing_moduli=[M for M in MODULI if obstructed(m, n, M)]))
certs = [(r['m'], r['n'], r['obstructing_moduli'][0]) for r in rows if r['obstructing_moduli']]
free = [(r['m'], r['n']) for r in rows if not r['obstructing_moduli']]
print('pairs:', len(pairs), '| excluded by a congruence:', len(certs), '| not excluded:', len(free))
print('smallest obstructing modulus:', dict(sorted(Counter(c[2] for c in certs).items())))
print('not excluded by a congruence:', free)

try:
    import cypari2
    pari = cypari2.Pari()
    pari.allocatemem(2 * 10**9)
    for r in rows:
        a, b = (r['m']**2 - r['n']**2) ** 2, (r['m']**2 + r['n']**2) ** 2
        E = pari.ellinit([0, -(a + b), 0, a * b, 0])
        rk = pari.ellrank(E)
        r['rank_lower'], r['rank_upper'] = int(rk[0]), int(rk[1])
        r['torsion'] = [int(x) for x in pari.elltors(E)[1]]
    print('torsion structures:', dict(Counter(tuple(r['torsion']) for r in rows)))
    print('rank bounds:', dict(Counter((r['rank_lower'], r['rank_upper']) for r in rows)))
    rank0 = [r for r in rows if r['rank_upper'] == 0]
    rest = [r for r in rows if r['rank_upper'] != 0]

    def first(r):
        for M in (32, 25, 7, 23):
            if M in r['obstructing_moduli']:
                return M
    print('rank 0 proved:', len(rank0), '| others:', len(rest))
    print('others, first obstruction in the order 32, 25, 7, 23:', dict(Counter(first(r) for r in rest)))
    print('others without an obstruction:', [(r['m'], r['n']) for r in rest if not r['obstructing_moduli']])
    print('rank-0 pairs that also have an obstruction:', sum(1 for r in rank0 if r['obstructing_moduli']),
          'of', len(rank0))
    print('rank-0 pairs without an obstruction:', [(r['m'], r['n']) for r in rank0 if not r['obstructing_moduli']])
except ImportError:
    print('cypari2 not installed: ranks not recomputed')

json.dump(rows, open('g1_audit.json', 'w'), indent=0)

if '--lean' in sys.argv:
    path = sys.argv[sys.argv.index('--lean') + 1]
    lines = []
    def mask(M):
        return sum(1 << x for x in {r * r % M for r in range(M)})
    for k in range(0, len(certs), 6):
        lines.append('  ' + ', '.join(f'({m}, {n}, {M}, {mask(M)})' for (m, n, M) in certs[k:k + 6]))
    body = ',\n'.join(lines)
    open(path, 'w', encoding='utf-8').write(f'''import MagicSquareOfSquares.G1

/-!
# Certificates for the G1 family with `m, n ≤ 20`

This file is generated by `scripts/g1_audit.py`. Do not edit it by hand.

For each listed pair `(m, n)` with modulus `M` and mask `S`, the kernel checks `S = sqMask M`
and evaluates `obstructs m n M S`. So for
these {len(certs)} pairs no rational `t` makes the three diagonal cells of the G1 family
squares, and the G1 family with these parameters contains no magic square of nine squares.

## Main results

* `certificates`: the list of tuples `(m, n, M, S)`.
* `certificates_valid`: every check succeeds.
* `no_point`: the conclusion for each listed pair.
-/

namespace MagicSquareOfSquares.G1

/-- Tuples `(m, n, M, S)` with `S = sqMask M` such that `obstructs m n M S` holds. -/
def certificates : List (ℕ × ℕ × ℕ × ℕ) := [
{body}]

/-- Every listed check succeeds. This is evaluated by the kernel. -/
theorem certificates_valid :
    certificates.all (fun c => decide (0 < c.2.2.1) && (c.2.2.2 == sqMask c.2.2.1) &&
      obstructs c.1 c.2.1 c.2.2.1 c.2.2.2) = true := by
  decide +kernel

/-- The list has {len(certs)} entries. -/
theorem certificates_length : certificates.length = {len(certs)} := by
  decide

/-- The listed pairs `(m, n)` are distinct. -/
theorem certificates_nodup : (certificates.map fun c => (c.1, c.2.1)).Nodup := by
  decide +kernel

/-- For each listed pair `(m, n)`, no rational `t` makes the three diagonal cells
`m² + n²t²`, `(m² + n²)(t² + 1)/2`, `n² + m²t²` of the G1 family all squares. -/
theorem no_point {{m n M S : ℕ}} (hc : (m, n, M, S) ∈ certificates) (t : ℚ) :
    ¬(IsSquare ((m : ℚ) ^ 2 + (n : ℚ) ^ 2 * t ^ 2) ∧
      IsSquare (((m : ℚ) ^ 2 + (n : ℚ) ^ 2) * (t ^ 2 + 1) / 2) ∧
      IsSquare ((n : ℚ) ^ 2 + (m : ℚ) ^ 2 * t ^ 2)) := by
  have h := List.all_eq_true.mp certificates_valid (m, n, M, S) hc
  simp only [Bool.and_eq_true, decide_eq_true_eq, beq_iff_eq] at h
  exact no_point_of_obstructs h.1.1 h.1.2 h.2 t

/-- The pair `(13, 3)`: excluded by a congruence modulo 7. -/
theorem no_point_13_3 (t : ℚ) :
    ¬(IsSquare (((13 : ℕ) : ℚ) ^ 2 + ((3 : ℕ) : ℚ) ^ 2 * t ^ 2) ∧
      IsSquare ((((13 : ℕ) : ℚ) ^ 2 + ((3 : ℕ) : ℚ) ^ 2) * (t ^ 2 + 1) / 2) ∧
      IsSquare (((3 : ℕ) : ℚ) ^ 2 + ((13 : ℕ) : ℚ) ^ 2 * t ^ 2)) :=
  no_point (M := 7) (S := 23) (by decide) t

/-- The pair `(19, 11)`: excluded by a congruence modulo 7. -/
theorem no_point_19_11 (t : ℚ) :
    ¬(IsSquare (((19 : ℕ) : ℚ) ^ 2 + ((11 : ℕ) : ℚ) ^ 2 * t ^ 2) ∧
      IsSquare ((((19 : ℕ) : ℚ) ^ 2 + ((11 : ℕ) : ℚ) ^ 2) * (t ^ 2 + 1) / 2) ∧
      IsSquare (((11 : ℕ) : ℚ) ^ 2 + ((19 : ℕ) : ℚ) ^ 2 * t ^ 2)) :=
  no_point (M := 7) (S := 23) (by decide) t

end MagicSquareOfSquares.G1
''')
    print('wrote', path, 'with', len(certs), 'certificates')
