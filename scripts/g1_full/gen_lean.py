#!/usr/bin/env python3
"""Writes MagicSquareOfSquares/G1FullCertificates.lean from modp_classes.txt.

The Lean file contains the table of obstructed classes (checked by the kernel), and the theorem
that for coprime 1 <= n < m <= 200, outside an explicit list of 60 pairs, no rational t makes
the five cells of the G1 family squares."""
import math, os
here = os.path.dirname(os.path.abspath(__file__))
table = {}
for line in open(os.path.join(here, 'modp_classes.txt')):
    p, r = map(int, line.split()); table.setdefault(p, []).append(r)
assert all(r < p for p, rs in table.items() for r in rs)
primes = sorted(table)
mask = lambda p: sum(1 << s for s in {x * x % p for x in range(p)})
issq = lambda x: math.isqrt(x) ** 2 == x
exc = [(m, n) for m in range(2, 201) for n in range(1, m) if math.gcd(m, n) == 1
       and (issq(m * m + n * n) or ((m * m + n * n) % 2 == 0 and issq((m * m + n * n) // 2)))]
rows = ',\n'.join(f'  ({p}, {mask(p)}, {sorted(table[p])})' for p in primes)
L = f'''import MagicSquareOfSquares.G1Full
import MagicSquareOfSquares.G1Classes
import MagicSquareOfSquares.G1Primes

/-!
# The G1 family with all nine cells: certificates

Generated by `scripts/g1_full/gen_lean.py`. Do not edit by hand.

* `fullTable`: for each of {len(primes)} primes `p`, the mask of squares modulo `p` and the ratios `r`
  for which the five-form check fails modulo `p` ({sum(len(v) for v in table.values())} classes in all).
  `fullTable_valid` is evaluated by the Lean kernel.
* `no_solution_le_200`: for coprime `1 ≤ n < m ≤ 200` outside `exceptions200`, no rational `t`
  makes the five cells squares. The {len(exc)} exceptions are the pairs for which `m² + n²` or
  `(m² + n²)/2` is a square (`exceptions200_spec`); for those the system has a degenerate
  rational solution.
-/

namespace MagicSquareOfSquares.G1

/-- `(p, S, rs)`: a prime, the mask of squares modulo `p`, and the obstructed ratios. -/
def fullTable : List (ℕ × ℕ × List ℕ) := [
{rows}]

/-- One table entry: the mask is right and the check succeeds for every listed ratio. -/
def fullOk (e : ℕ × ℕ × List ℕ) : Bool :=
  decide (e.2.1 = sqMask e.1) && e.2.2.all fun r => obstructsFull r 1 e.1 e.1 e.2.1

theorem fullTable_valid : fullTable.all fullOk = true := by decide +kernel

/-- The primes of the table. -/
def primeList : List ℕ := {primes}

theorem fullTable_primes : fullTable.map Prod.fst = primeList := by decide +kernel

theorem prime_of_mem_primeList {{p : ℕ}} (h : p ∈ primeList) : p.Prime := by
  simp only [primeList, List.mem_cons, List.mem_nil_iff, or_false] at h
  rcases h with {' | '.join(['rfl'] * len(primes))} <;> norm_num

/-- `certified m n`: some table entry applies to `(m, n)`. -/
def certified (m n : ℕ) : Bool :=
  fullTable.any fun e =>
    decide (n % e.1 ≠ 0) && e.2.2.any fun r => decide (m % e.1 = r * n % e.1)

theorem no_solution_of_certified {{m n : ℕ}} (h : certified m n = true) (t : ℚ) :
    ¬FullSquares m n t := by
  unfold certified at h
  obtain ⟨⟨p, S, rs⟩, he, h2⟩ := List.any_eq_true.mp h
  simp only [Bool.and_eq_true, decide_eq_true_eq, List.any_eq_true] at h2
  obtain ⟨hn, r, hr, hmr⟩ := h2
  have hv := List.all_eq_true.mp fullTable_valid _ he
  simp only [fullOk, Bool.and_eq_true, decide_eq_true_eq, List.all_eq_true] at hv
  obtain ⟨hS, hall⟩ := hv
  have hp : p.Prime := prime_of_mem_primeList (by
    rw [← fullTable_primes]
    exact List.mem_map_of_mem (f := Prod.fst) he)
  exact no_solution_of_ratio hp hS (hall r hr) hmr hn t

/-- Primes `5 mod 8` used for the few pairs that the table does not cover. -/
def fivePrimes : List ℕ := [13, 29]

theorem fivePrimes_spec {{p : ℕ}} (h : p ∈ fivePrimes) : p.Prime ∧ p % 8 = 5 := by
  simp only [fivePrimes, List.mem_cons, List.mem_nil_iff, or_false] at h
  rcases h with rfl | rfl <;> constructor <;> norm_num

/-- `fiveCert m n`: one of these primes divides `m² + n²` exactly once and does not divide `n`. -/
def fiveCert (m n : ℕ) : Bool :=
  fivePrimes.any fun p =>
    decide ((m * m + n * n) % p = 0 ∧ (m * m + n * n) % (p * p) ≠ 0 ∧ n % p ≠ 0)

/-- `closed m n`: one of the proved obstructions applies. -/
def closed (m n : ℕ) : Bool :=
  certified m n || cond8 m n || cond32 m n || fiveCert m n

theorem no_solution_of_closed {{m n : ℕ}} (h : closed m n = true) (t : ℚ) :
    ¬FullSquares m n t := by
  unfold closed at h
  simp only [Bool.or_eq_true] at h
  rcases h with ((h | h) | h) | h
  · exact no_solution_of_certified h t
  · exact fun hf => no_point_of_two_mod_four
      (by simpa only [cond8, decide_eq_true_eq] using h) t hf.1
  · exact fun hf => no_point_of_odd
      (by simpa only [cond32, decide_eq_true_eq] using h) t hf.1
  · unfold fiveCert at h
    obtain ⟨p, hp, h3⟩ := List.any_eq_true.mp h
    simp only [decide_eq_true_eq] at h3
    obtain ⟨d1, d2, d3⟩ := h3
    exact fun hf => no_point_of_exactly_divides (fivePrimes_spec hp).1 (fivePrimes_spec hp).2
      (Nat.dvd_of_mod_eq_zero d1) (fun hd => d2 (Nat.mod_eq_zero_of_dvd hd))
      (fun hd => d3 (Nat.mod_eq_zero_of_dvd hd)) t hf.1

/-- The pairs with `m ≤ 200` for which `m² + n²` or `(m² + n²)/2` is a square. -/
def exceptions200 : List (ℕ × ℕ) := {exc}

theorem exceptions200_length : exceptions200.length = {len(exc)} := by decide +kernel

/-- Every exception has `m² + n² = k²` or `m² + n² = 2k²` for some `k`. -/
theorem exceptions200_spec : exceptions200.all (fun e =>
    (List.range 300).any fun k => e.1 * e.1 + e.2 * e.2 == k * k ||
      e.1 * e.1 + e.2 * e.2 == 2 * (k * k)) = true := by decide +kernel

/-- The census: every coprime pair `1 ≤ n < m ≤ 200` is closed or is an exception. -/
def census200 : Bool :=
  (List.range 201).all fun m => (List.range m).all fun n =>
    !(Nat.gcd m n == 1 && decide (0 < n)) || closed m n || decide ((m, n) ∈ exceptions200)

theorem census200_ok : census200 = true := by decide +kernel

/-- **For coprime `1 ≤ n < m ≤ 200` outside the 60 exceptions, no rational `t` makes the five
free cells of the G1 family squares.** -/
theorem no_solution_le_200 {{m n : ℕ}} (hn0 : 0 < n) (hn : n < m) (hm : m ≤ 200)
    (hcop : Nat.Coprime m n)
    (hex : (m, n) ∉ exceptions200) (t : ℚ) : ¬FullSquares m n t := by
  have h := census200_ok
  unfold census200 at h
  have h1 := List.all_eq_true.mp h m (List.mem_range.mpr (by omega))
  have h2 := List.all_eq_true.mp h1 n (List.mem_range.mpr hn)
  have hg : (Nat.gcd m n == 1 && decide (0 < n)) = true := by
    rw [Bool.and_eq_true, beq_iff_eq, decide_eq_true_eq]
    exact ⟨hcop, hn0⟩
  simp only [hg, Bool.not_true, Bool.false_or, Bool.or_eq_true, decide_eq_true_eq] at h2
  rcases h2 with h2 | h2
  · exact no_solution_of_closed h2 t
  · exact absurd h2 hex

end MagicSquareOfSquares.G1
'''
open(os.path.join(here, '..', '..', 'MagicSquareOfSquares', 'G1FullCertificates.lean'), 'w', encoding='utf-8').write(L)
print('primes', len(primes), 'classes', sum(len(v) for v in table.values()), 'exceptions', len(exc))
