#!/usr/bin/env python3
"""Writes MagicSquareOfSquares/G1SizeCheck.lean: for every two exceptional pairs (M, N) and (p, q)
with m <= 1000, the five forms for (p, q) at (N, M) and at (M, N) are not all squares, because one
of them is a non-residue modulo one of the 34 primes. The kernel checks this in parts."""
import math, os, re
here = os.path.dirname(os.path.abspath(__file__))
src = open(os.path.join(here, '..', '..', 'MagicSquareOfSquares', 'G1Census1000.lean'), encoding='utf-8').read()
exc = eval(re.search(r'def exceptions1000 : List \(ℕ × ℕ\) := (\[.*?\])\n', src).group(1))
# The 34 primes of the sieve are all +-1 mod 8, so they never detect a form of the shape 2 x square.
# Here any modulus will do; small primes of both kinds are used, those that are 3 or 5 mod 8 first.
primes = [3, 5, 11, 13, 19, 29, 37, 43, 7, 17, 23, 31, 41, 47, 53, 59, 61, 67]
sq = {p: {x * x % p for x in range(p)} for p in primes}
used = [0] * (len(primes) + 1)
def bad(p, q, u, v):
    f2 = 2 * (p * p + q * q) * (u * u + v * v)
    fs = (p*p*v*v + q*q*u*u, f2, q*q*v*v + p*p*u*u, f2 - 8*p*q*u*v, f2 + 8*p*q*u*v)
    for k, P in enumerate(primes):
        if not all(x % P in sq[P] for x in fs): used[k + 1] += 1; return True
    return False
assert all(bad(p, q, N, M) and bad(p, q, M, N) for (M, N) in exc for (p, q) in exc)
print('primes needed (count by position):', used[1:])
mask = lambda p: sum(1 << r for r in sq[p])
K = 15; size = -(-len(exc) // K)
parts = [exc[i:i + size] for i in range(0, len(exc), size)]
pat = 'h'
for _ in parts[1:]: pat = '(' + pat + ' | h)'
L = ['import MagicSquareOfSquares.G1Census1000', '',
     '/-!', '# The exceptional pairs against each other', '',
     'Generated by `scripts/g1_full/gen_sizecheck.py`. Do not edit by hand.', '',
     f'For any two of the {len(exc)} exceptional pairs `(M, N)` and `(p, q)`, the five forms for `(p, q)` at',
     '`(N, M)` and at `(M, N)` are not all squares: one of them is a non-residue modulo one of the',
     f'small primes of `sizePrimes`. The kernel checks all {2 * len(exc) ** 2:,} cases in {len(parts)} parts.', '-/', '',
     'namespace MagicSquareOfSquares.G1', '',
     '/-- Small primes with their masks of squares. -/',
     'def sizePrimes : List (ℕ × ℕ) := ' + str([(p, mask(p)) for p in primes]), '',
     'theorem sizePrimes_valid :',
     '    (sizePrimes.all fun e => decide (0 < e.1 ∧ e.2 = sqMask e.1)) = true := by decide +kernel', '',
     '/-- Some prime of the list shows that the five forms for `(p, q)` at `(u, v)` are not all squares. -/',
     'def badQuad (p q u v : ℕ) : Bool := sizePrimes.any fun e => !sqFive p q e.1 e.2 u v', '',
     '/-- The check for two exceptional pairs. -/',
     'def quadOk (e1 e2 : ℕ × ℕ) : Bool :=', '  badQuad e2.1 e2.2 e1.2 e1.1 && badQuad e2.1 e2.2 e1.1 e1.2', '',
     'theorem exceptions1000_pos :', '    (exceptions1000.all fun e => decide (0 < e.2 ∧ e.2 < e.1)) = true := by decide +kernel', '']
for k, part in enumerate(parts):
    L += [f'def excPart{k} : List (ℕ × ℕ) := {part}', '',
          f'theorem quadPart{k} :', f'    (excPart{k}.all fun e1 => exceptions1000.all fun e2 => quadOk e1 e2) = true := by', '  decide +kernel', '']
L += ['theorem exceptions1000_parts :', '    exceptions1000 = ' + ' ++ '.join(f'excPart{k}' for k in range(len(parts))) + ' := by', '  decide +kernel', '',
      'theorem quadOk_of_mem {e1 e2 : ℕ × ℕ} (h1 : e1 ∈ exceptions1000) (h2 : e2 ∈ exceptions1000) :',
      '    quadOk e1 e2 = true := by', '  rw [exceptions1000_parts] at h1', '  simp only [List.mem_append] at h1', f'  rcases h1 with {pat}']
L += [f'  · exact List.all_eq_true.mp (List.all_eq_true.mp quadPart{k} e1 h) e2 h2' for k in range(len(parts))]
L += ['', 'end MagicSquareOfSquares.G1', '']
open(os.path.join(here, '..', '..', 'MagicSquareOfSquares', 'G1SizeCheck.lean'), 'w', encoding='utf-8').write('\n'.join(L))
print('exceptions', len(exc), 'parts', len(parts), 'cases', 2 * len(exc) ** 2)
