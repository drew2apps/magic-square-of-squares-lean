from fractions import Fraction as F
import sys

class K:
    """a + b r with r^2 = 2, a, b rational."""
    __slots__ = ("a", "b")
    def __init__(s, a, b=0): s.a = F(a); s.b = F(b)
    def _c(o): return o if isinstance(o, K) else K(o)
    def __add__(s, o): o = K._c(o); return K(s.a + o.a, s.b + o.b)
    __radd__ = __add__
    def __neg__(s): return K(-s.a, -s.b)
    def __sub__(s, o): return s + (-K._c(o))
    def __rsub__(s, o): return K._c(o) - s
    def __mul__(s, o): o = K._c(o); return K(s.a * o.a + 2 * s.b * o.b, s.a * o.b + s.b * o.a)
    __rmul__ = __mul__
    def inv(s):
        n = s.a * s.a - 2 * s.b * s.b
        assert n != 0
        return K(s.a / n, -s.b / n)
    def __truediv__(s, o): return s * K._c(o).inv()
    def __eq__(s, o): o = K._c(o); return s.a == o.a and s.b == o.b
    def __hash__(s): return hash((s.a, s.b))
    def __repr__(s): return f"{s.a}+{s.b}r"

d = K(2, 1); A2 = 8 * d; A4 = -8 * d * d

def on(P):
    x, y = P
    return y * y == x * x * x + A2 * x * x + A4 * x

def slope_dbl(P):
    x, y = P
    return (3 * x * x + 2 * A2 * x + A4) / (2 * y)

def add(P, Q):
    if P is None: return Q
    if Q is None: return P
    (x1, y1), (x2, y2) = P, Q
    if x1 == x2 and y1 == -y2: return None
    L = slope_dbl(P) if x1 == x2 else (y1 - y2) / (x1 - x2)
    x3 = L * L - A2 - x1 - x2
    return (x3, -(L * (x3 - x1) + y1))

def neg(P): return None if P is None else (P[0], -P[1])

def mul(n, P):
    R = None
    for _ in range(n): R = add(R, P)
    return R

def order(P):
    n, R = 1, P
    while R is not None:
        R = add(R, P); n += 1
        assert n < 100
    return n

# The nine affine points of the Lean file (coordinates a + b r).
PTS = {
    "T": (K(0), K(0)), "A": (K(4), K(0, 8)), "Am": (K(4), K(0, -8)),
    "B": (K(-4), K(16, 8)), "Bm": (K(-4), K(-16, -8)),
    "C": (K(12, 8), K(80, 56)), "Cm": (K(12, 8), K(-80, -56)),
    "D": (K(-12, -8), K(-32, -24)), "Dm": (K(-12, -8), K(32, 24)),
}

def check_group():
    for k, P in PTS.items():
        assert on(P), k
    G = set(PTS.values()) | {None}
    assert len(G) == 10
    for P in G:
        for Q in G:
            assert add(P, Q) in G
    Dg = PTS["D"]
    assert {mul(n, Dg) for n in range(10)} == G and mul(10, Dg) is None
    # doublings and slopes used in Lean
    dbl = [("A", "Cm", K(2, 4)), ("C", "A", K(6, 2)), ("B", "A", K(-2, -2)), ("D", "C", K(-2))]
    for s, t, L in dbl:
        assert slope_dbl(PTS[s]) == L, (s, slope_dbl(PTS[s]))
        assert add(PTS[s], PTS[s]) == PTS[t], (s, t)
    for s in ["A", "B", "C", "D"]:
        assert neg(PTS[s]) == PTS[s + "m"]
    ords = {k: order(P) for k, P in PTS.items()}
    assert ords == {"T": 2, "A": 5, "Am": 5, "B": 10, "Bm": 10, "C": 5, "Cm": 5, "D": 10, "Dm": 10}, ords
    absc = {P[0] for P in PTS.values()}
    assert absc == {K(0), K(4), K(-4), K(12, 8), K(-12, -8)}
    return ords

def red(z, p, r):
    """z = a + b r in Z[r] -> (a + b*r) mod p for the root r of t^2 - 2 mod p."""
    assert z.a.denominator == 1 and z.b.denominator == 1
    return (int(z.a) + int(z.b) * r) % p

def reduced_curve(p, r):
    a2 = red(A2, p, r); a4 = red(A4, p, r)
    return a2, a4

def points_mod(p, a2, a4):
    return [(x, y) for x in range(p) for y in range(p) if (y * y - (x ** 3 + a2 * x * x + a4 * x)) % p == 0]

def check_reduction(p=7, r=3):
    assert (r * r - 2) % p == 0
    a2, a4 = reduced_curve(p, r)
    assert (a2, a4) == (5, 3), (a2, a4)
    disc = 98304 * (2 + r) ** 6 % p          # Delta = 98304 (2 + r)^6 (LemmaDBridge.Δ_E1K)
    assert disc != 0
    # Delta of y^2 = x^3 + a2 x^2 + a4 x: 16 a4^2 (a2^2 - 4 a4)
    assert (16 * a4 ** 2 * (a2 * a2 - 4 * a4)) % p == disc
    pts = points_mod(p, a2, a4)
    assert len(pts) + 1 == 10
    assert sorted(pts) == sorted([(0, 0), (4, 3), (4, 4), (3, 5), (3, 2), (1, 3), (1, 4), (6, 1), (6, 6)])
    images = {k: (red(P[0], p, r), red(P[1], p, r)) for k, P in PTS.items()}
    assert sorted(images.values()) == sorted(pts), images
    return pts, images

def check_unramified():
    assert (10 * 10 - 2) % 49 == 0 and 10 % 7 == 3
    # x = a + b r in ker(psi7) iff 7 | a + 3 b; then 7 | a + 10 b, so products vanish mod 49
    for a in range(49):
        for b in range(49):
            if (a + 3 * b) % 7 == 0:
                assert (a + 10 * b) % 7 == 0
    assert 7 % 49 != 0
    # exhaustive over Z[r]/49: products of two elements of ker(psi7) lie in ker(psi49)
    # (psi49(a + b r) = a + 10 b mod 49 depends only on a, b mod 49)
    ker = [(a, b) for a in range(49) for b in range(49) if (a + 3 * b) % 7 == 0]
    assert len(ker) == 343
    for (a, b) in ker:
        for (c, e) in ker:
            pa, pb = a * c + 2 * b * e, a * e + b * c
            assert (pa + 10 * pb) % 49 == 0
    # psi49 is multiplicative on Z[r]: (a + 10b)(c + 10e) = (ac + 2be) + 10(ae + bc) mod 49
    for a in range(49):
        for b in range(0, 49, 6):
            for c in range(0, 49, 5):
                for e in range(0, 49, 7):
                    assert ((a + 10 * b) * (c + 10 * e) - ((a * c + 2 * b * e) + 10 * (a * e + b * c))) % 49 == 0

def check_pari():
    try:
        import cypari2
    except ImportError:
        print("PARI check skipped (cypari2 not available)")
        return None
    pari = cypari2.Pari()
    nf = pari("nfinit(t^2-2)")
    E = pari.ellinit(pari("[0, 8*(2+t), 0, -8*(2+t)^2, 0]"), nf)
    tors = pari.elltors(E)
    assert int(tors[0]) == 10 and [int(c) for c in tors[1]] == [10], tors
    # independent of the class K above: PARI's group law and orders over nf for the points used in Lean
    def nfpt(P):
        (x, y) = P
        return pari(f"[{x.a} + {x.b}*t, {y.a} + {y.b}*t]")
    for s_, t_ in [("A", "Cm"), ("C", "A"), ("B", "A"), ("D", "C")]:
        lhs = pari.elladd(E, nfpt(PTS[s_]), nfpt(PTS[s_]))
        rhs = pari.lift(pari.Mod(nfpt(PTS[t_]), pari("t^2-2")))
        assert pari.lift(lhs) == rhs, (s_, lhs, rhs)
    # the comparison is not vacuous: 2A is -C, not C
    assert pari.lift(pari.elladd(E, nfpt(PTS["A"]), nfpt(PTS["A"]))) != pari.lift(pari.Mod(nfpt(PTS["C"]), pari("t^2-2")))
    pari_orders = {k: int(pari.ellorder(E, nfpt(P))) for k, P in PTS.items()}
    assert pari_orders == {"T": 2, "A": 5, "Am": 5, "B": 10, "Bm": 10, "C": 5, "Cm": 5, "D": 10, "Dm": 10}, pari_orders
    cards = []
    for P in pari.idealprimedec(nf, 7):
        Ep = pari.ellinit(E, P)        # reduction at P (good reduction: 7 does not divide the discriminant)
        cards.append(int(pari.ellcard(Ep)))
    assert cards == [10, 10], cards
    return str(tors), cards

def negative_tests():
    refused = 0
    # wrong residue map r -> 2 mod 7
    try:
        check_reduction(7, 2); print("NEGATIVE TEST FAILED: r -> 2 accepted"); sys.exit(1)
    except AssertionError: refused += 1
    # wrong reduced curve: a4 = 4 instead of 3 has a different number of points / point set
    pts = points_mod(7, 5, 4)
    if sorted(pts) != sorted([(0, 0), (4, 3), (4, 4), (3, 5), (3, 2), (1, 3), (1, 4), (6, 1), (6, 6)]): refused += 1
    else: print("NEGATIVE TEST FAILED: wrong curve accepted"); sys.exit(1)
    # forged point (4, 4r)
    if not on((K(4), K(0, 4))): refused += 1
    else: print("NEGATIVE TEST FAILED: forged point accepted"); sys.exit(1)
    # wrong count 11
    if len(points_mod(7, 5, 3)) + 1 != 11: refused += 1
    else: print("NEGATIVE TEST FAILED"); sys.exit(1)
    # wrong lift mod 49 (r -> 3): 3^2 - 2 = 7 not 0 mod 49
    if (3 * 3 - 2) % 49 != 0: refused += 1
    else: print("NEGATIVE TEST FAILED"); sys.exit(1)
    # wrong doubling 2A = C
    if add(PTS["A"], PTS["A"]) != PTS["C"]: refused += 1
    else: print("NEGATIVE TEST FAILED"); sys.exit(1)
    # ramification certificate modulo 21 instead of 49: 7 * 7 = 49 = 7 != 0 mod 21
    if any((a * b) % 21 != 0 for a in range(0, 21, 7) for b in range(0, 21, 7)): refused += 1
    else: print("NEGATIVE TEST FAILED"); sys.exit(1)
    return refused

