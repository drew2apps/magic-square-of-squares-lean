#!/usr/bin/env python3
"""Generator of MagicSquareOfSquares/TwoDescentCertificates.lean (UNIFORM_RANK.md, Theorem 2, at the 127 ratios).

Untrusted: it only chooses the numbers.  Lean checks every one of them (TwoDescentMap.lean, `theorem2_of`).
For each coprime ratio (m, n), 1 <= n < m <= 1000, with m^2 + n^2 = 2k^2 (the list of sigma_twice.py), and for both
curves E+ = Eplus m n and E- = Eplus m (-n), the five non-square facts that `theorem2_of` needs are certified by
square-root brackets s^2 < N < (s+1)^2 (or N < 0):

    H(m, n), H(m, -n), H(m, n) H(m, -n), 2mn, -2mn      (H(m, n) = m^4 - 2m^3 n + 2m^2 n^2 + 2m n^3 + n^4).

It also checks (crosscheck) that the Lean curve `Eplus m (+-n)` is, coefficient for coefficient, the model
sigma_exact.model(m, n, +-2) of E+ and E- used by sigma_twice.py and sigma_generic.py, on all 254 curves.

Exact integer arithmetic only (math.isqrt).  Without --write the output is compared with the committed file and
the script fails on any difference.  --negative runs forged inputs that the generator must refuse (also run by
default, so its lines are part of the output).

Written by an AI model; not read by a person.
"""
import os, sys
from math import gcd, isqrt

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, '..', '..', 'MagicSquareOfSquares', 'TwoDescentCertificates.lean')


def H(m, n):
    return m**4 - 2*m**3*n + 2*m*m*n*n + 2*m*n**3 + n**4


def ratios():
    out = []
    for m in range(2, 1001):
        for n in range(1, m):
            S = m*m + n*n
            if gcd(m, n) == 1 and S % 2 == 0 and isqrt(S // 2)**2 == S // 2 and isqrt(S)**2 != S:
                out.append((m, n, isqrt(S // 2)))
    return out


def bracket(N):
    """Lean term proving ¬ IsSquare of an expression equal to N (N an integer); refuses a square."""
    if N < 0:
        return '(not_isSquare_of_neg (by norm_num))'
    s = isqrt(N)
    if s * s == N:
        raise ValueError('square: %d' % N)
    assert s * s < N < (s + 1) * (s + 1)
    return None, N, s


def cert(m, n, k):
    """Lean text of `Theorem2At m n k` (n may be negative: the curve E- of the ratio (m, -n))."""
    assert m*m + n*n == 2*k*k and k > 0 and m != 0 and n != 0 and m + n != 0 and m - n != 0
    facts = [(H(m, n), 'genH'), (H(m, -n), 'genH'), (H(m, n) * H(m, -n), 'genH'), (2*m*n, None), (-2*m*n, None)]
    args = []
    for N, unf in facts:
        b = bracket(N)
        if isinstance(b, str):
            args.append(b)
        else:
            _, N, s = b
            ev = '(by unfold genH; norm_num)' if unf else '(by norm_num)'
            args.append('(nsq %d %d %s (by norm_num) (by norm_num))' % (N, s, ev))
    q = lambda v: '(%d)' % v if v < 0 else '%d' % v
    name = 't2_%d_%d_%s' % (m, abs(n), 'p' if n > 0 else 'm')
    head = 'theorem %s : Theorem2At %s %s %s :=\n  theorem2_of %s %s %s (by norm_num) (by norm_num) (by norm_num) (by norm_num) (by norm_num)\n' % (
        name, q(m), q(n), q(k), q(m), q(n), q(k))
    return name, head + ''.join('    %s\n' % a for a in args)


HEADER = '''import MagicSquareOfSquares.TwoDescentMap

/-!
# `UNIFORM_RANK.md` Theorem 2 at the 127 twice-square ratios with `m ≤ 1000`

GENERATED by `scripts/g1_full/two_descent_certs.py` (do not edit; rerun with `--write`).  Written by an AI
model; not read by a person.

For each coprime ratio `(m, n)`, `1 ≤ n < m ≤ 1000`, with `m² + n² = 2k²` (the 127 ratios of
`scripts/g1_full/sigma_twice.py`), `Theorem2At m n k` (curve `E⁺`) and `Theorem2At m (−n) k` (curve `E⁻`, which is
`Eplus m (−n)`): on that curve the points `R`, `Q`, `T` are independent in `E(ℚ)/2E(ℚ)`.  Each instance is
`theorem2_of` of `TwoDescentMap.lean` with its five non-square facts proved by square-root brackets
`s² < N < (s + 1)²` (`nsq`) or by `N < 0`.

`twiceSquareRatios` is the list; `twiceSquareRatios_ok` checks (by `decide +kernel`) that it has 127 entries and
that each is coprime with `n < m ≤ 1000` and `m² + n² = 2k²`.  That the list contains *every* such ratio is the
enumeration of the generator (and of `sigma_twice.py`), not a Lean statement.  Out of scope: Lemmas B and D of
`UNIFORM_RANK.md`, which would give the non-square facts for every ratio at once.
-/

namespace MagicSquareOfSquares.TwoDescent

open MagicSquareOfSquares.G1

set_option maxRecDepth 4000

'''


def generate():
    rs = ratios()
    assert len(rs) == 127, len(rs)
    parts = [HEADER]
    names = []
    for (m, n, k) in rs:
        for sgn in (1, -1):
            name, txt = cert(m, sgn * n, k)
            names.append(name)
            parts.append(txt + '\n')
    parts.append('/-- The 127 ratios `(m, n, k)`. -/\ndef twiceSquareRatios : List (ℕ × ℕ × ℕ) :=\n  [' +
                 ',\n   '.join(', '.join('(%d, %d, %d)' % r for r in rs[i:i + 6]) for i in range(0, len(rs), 6)) + ']\n\n')
    parts.append('theorem twiceSquareRatios_ok : twiceSquareRatios.length = 127 ∧\n'
                 '    ∀ p ∈ twiceSquareRatios, Nat.gcd p.1 p.2.1 = 1 ∧ 0 < p.2.1 ∧ p.2.1 < p.1 ∧ p.1 ≤ 1000 ∧\n'
                 '      p.1 ^ 2 + p.2.1 ^ 2 = 2 * p.2.2 ^ 2 := by\n  decide +kernel\n\n')
    parts.append('/-- **Theorem 2 at all 127 ratios, both curves.** -/\n'
                 'theorem theorem2_twiceSquare : ∀ p ∈ twiceSquareRatios,\n'
                 '    Theorem2At (p.1 : ℚ) (p.2.1 : ℚ) (p.2.2 : ℚ) ∧ Theorem2At (p.1 : ℚ) (-(p.2.1 : ℚ)) (p.2.2 : ℚ) := by\n'
                 '  simp only [twiceSquareRatios, List.forall_mem_cons, Nat.cast_ofNat, Nat.cast_one]\n'
                 '  exact ⟨' + ',\n    '.join('⟨%s, %s⟩' % (names[2 * i], names[2 * i + 1]) for i in range(len(rs))) +
                 ',\n    fun _ h => by simp at h⟩\n\n')
    parts.append('end MagicSquareOfSquares.TwoDescent\n')   # no #print axioms in library files: scripts/Audit.lean covers them
    return ''.join(parts)


def negative():
    """Forged inputs that must be refused."""
    refused = 0
    # 1. a square-type ratio: no k with m^2 + n^2 = 2k^2
    try:
        cert(12, 5, 6); print('NOT refused: square-type ratio (12,5)'); sys.exit(1)
    except AssertionError:
        refused += 1
    # 2. a wrong k
    try:
        cert(7, 1, 4); print('NOT refused: k = 4 at (7,1)'); sys.exit(1)
    except AssertionError:
        refused += 1
    # 3. a square in place of a non-square (H replaced by the square 90000 = 300^2)
    try:
        bracket(90000); print('NOT refused: bracket of 300^2'); sys.exit(1)
    except ValueError:
        refused += 1
    # 4. H(m, n) is a square for some ratios that are not twice a square (UNIFORM_RANK.md section 6: (4,1))
    try:
        assert isqrt(H(4, 1))**2 == H(4, 1)
        bracket(H(4, 1)); print('NOT refused: H(4,1)'); sys.exit(1)
    except ValueError:
        refused += 1
    # 5. a forged bracket: s off by one must fail the bracket inequality
    N = H(7, 1); s = isqrt(N) + 1
    if s * s < N < (s + 1) * (s + 1):
        print('NOT refused: forged bracket'); sys.exit(1)
    refused += 1
    # 6. the cross-check can fail: the model of the other curve (z = -2) is not Eplus m n at (7,1)
    sys.path.insert(0, HERE)
    from sigma_exact import model
    M = model(7, 1, -2); S = 50; e = -2 * S**3; a = 16 * 49 * 64; b = 16 * 49 * 4096 * S * S
    if (M['a2'], M['a4'], M['a6']) == (a - e, b - a*e, -e*b):
        print('NOT refused: model(7,1,-2) taken for Eplus 7 1'); sys.exit(1)
    refused += 1
    print('negative: %d forged inputs refused' % refused)
    return refused


def crosscheck():
    """The Lean curve Eplus m (+-n) is the repository's model sigma_exact.model(m, n, +-2) (E+ and E-), coefficient
    for coefficient, on all 254 curves; Q = (0, 8kmn(m+n)^2 S^2) is the point (0, sqrt(a6)) of sigma_twice.py up
    to sign; and the point of z = +-2 has abscissa x(P) = -(m+n)^2 S^2 (P = R + R is `R_add_R` in Lean)."""
    sys.path.insert(0, HERE)
    from sigma_exact import model
    count = 0
    for (m, n, k) in ratios():
        for s, nn in ((2, n), (-2, -n)):
            M = model(m, n, s)
            S = m*m + nn*nn
            e = -2 * S**3; a = 16 * m*m * nn*nn * (m + nn)**2; b = 16 * m*m * nn*nn * (m + nn)**4 * S*S
            assert (M['a2'], M['a4'], M['a6']) == (a - e, b - a*e, -e*b), (m, n, s)
            yQ = 8 * k * m * nn * (m + nn)**2 * S*S
            assert yQ * yQ == M['a6'] and isqrt(M['a6']) == abs(yQ)
            # the point P of t = +-1 (z = +-2) of the model is the point xP of R_add_R (P = 2R in Lean)
            zp = 2 if s > 0 else -2
            assert M['A'] % (zp - M['z0']) == 0 and M['A'] // (zp - M['z0']) == -((m + nn)**2 * S*S)
            count += 1
    print('crosscheck: Eplus m (+-n) = sigma_exact.model(m, n, +-2), y(Q)^2 = a6, x(P) = -(m+n)^2 S^2 on %d curves' % count)


def main():
    if '--negative' in sys.argv:
        negative(); return
    txt = generate()
    negative()
    crosscheck()
    if '--write' in sys.argv:
        with open(OUT, 'w') as f:
            f.write(txt)
        print('written MagicSquareOfSquares/TwoDescentCertificates.lean')
    else:
        with open(OUT) as f:
            old = f.read()
        if old != txt:
            print('DIFFERS from MagicSquareOfSquares/TwoDescentCertificates.lean'); sys.exit(1)
        print('matches MagicSquareOfSquares/TwoDescentCertificates.lean')
    print('two_descent_certs OK: 127 ratios, 254 curves')


if __name__ == '__main__':
    main()
