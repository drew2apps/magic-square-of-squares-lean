#!/usr/bin/env python3
"""A 2-descent over K = Q(i) for elliptic curves with full 2-torsion over K.  EXPERIMENT.

E: y^2 = (x - e1)(x - e2)(x - e3), e_i in Z[i] distinct.  The map P -> (x - e1, x - e2) embeds E(K)/2E(K) in (K*/K*^2)^2
(at a point of order 2 the vanishing coordinate is replaced by the product of the other two differences).  The image lies in
the 2-Selmer group: the pairs (b1, b2) of S-units modulo squares whose class at every place v of S lies in the local image of
E(K_v)/2E(K_v).  S: the places above the rational primes dividing 2 N(prod (e_i - e_j)).  Z[i] is a principal ideal domain
with units generated by i, and -1 is a square, so the S-units modulo squares have the basis i, 1+i and the Gaussian primes of S.

Local image at v: generated here by actual points.  A sample x in K gives a point of E(K_v) when (x-e1)(x-e2)(x-e3) is a square
in K_v, decided exactly from the class labels of gauss_descent.py (which are tested against PARI's Hilbert symbols).  The
order of E(K_v)/2E(K_v) is known: 4 at an odd place, 16 at 1+i (it is #E(K_v)[2] times the index of 2 O_v in O_v).  Sampling
stops when that order is reached; if it is not reached the function returns None.  So a returned image is the full local
image, and the Selmer group is exact.

rank E(K) <= dim Sel - 2.

Tested in kdescent_test.py against PARI on curves defined over Q, where rank E(K) = rank E(Q) + rank E^(-1)(Q)."""
import os, sys, random
from math import gcd
import cypari2
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'gauss_descent'))
import gauss_descent as gd
pari = cypari2.Pari()

def gsub(x, y): return (x[0] - y[0], x[1] - y[1])
def gadd(x, y): return (x[0] + y[0], x[1] + y[1])
def gscale(c, x): return (c*x[0], c*x[1])
def gpow(x, k):
    r = (1, 0)
    for _ in range(k): r = gd.gmul(r, x)
    return r

# ---- unit classes at 1+i as vectors of F_2^3
def _unit_table():
    units = [(a, b) for a in range(8) for b in range(8) if (a + b) % 2]
    labels = sorted(set(gd.unit_class2(u) for u in units)); assert len(labels) == 8
    gens = []; span = {gd.unit_class2((1, 0)): (0, 0, 0)}
    for u in units:
        if len(gens) == 3: break
        lab = gd.unit_class2(u)
        if lab in span: continue
        k = len(gens); gens.append(u); new = {}
        for l, vec in span.items():
            rep = l; prod = ((rep[0]*u[0] - rep[1]*u[1]) % 8, (rep[0]*u[1] + rep[1]*u[0]) % 8)
            v2 = list(vec); v2[k] = 1; new[gd.unit_class2(prod)] = tuple(v2)
        span.update(new)
    assert len(span) == 8
    return span
UNIT2 = _unit_table()

class Place:
    """A place of K above the rational prime p; idx 0 or 1 for the two places of a split prime."""
    def __init__(s, p, idx, L):
        s.p = p; s.idx = idx; s.L = L; s.dim = 4 if p == 2 else 2
    def vec(s, z):
        """Class of the Gaussian integer z != 0 in K_v*/K_v*^2 as a tuple over F_2, or None if not determined."""
        c = s.L.cls(z)[s.idx]
        if c is None: return None
        if s.p == 2: return (c[0],) + UNIT2[c[1]]
        return (c[0], 0 if c[1] == 1 else 1)

def places_above(p):
    L = gd.Local(p)
    return [Place(p, 0, L)] + ([Place(p, 1, L)] if L.kind == 'split' else [])

# ---- linear algebra over F_2, vectors as Python ints
def to_int(v): return sum(b << i for i, b in enumerate(v))
def rank_basis(rows):
    basis = []                                          # reduced, with pivots
    for r in rows:
        for b in basis: r = min(r, r ^ b)
        if r: basis.append(r)
    return basis
def nullspace(rows, ncols):
    """Vectors x (ints) with <row, x> = 0 for all rows."""
    piv = {}; 
    for r in rows:
        for c, b in piv.items():
            if r >> c & 1: r ^= b
        if r:
            c = r.bit_length() - 1
            for c2 in list(piv):
                if piv[c2] >> c & 1: piv[c2] ^= r
            piv[c] = r
    free = [c for c in range(ncols) if c not in piv]; out = []
    for f in free:
        x = 1 << f
        for c, b in piv.items():
            if b >> f & 1: x |= 1 << c
        out.append(x)
    return out

def xor_vec(a, b): return tuple(x ^ y for x, y in zip(a, b))

def local_image(e, pl, rng, tries=4000):
    """Basis (ints over F_2^(2 dim)) of the image of E(K_v)/2E(K_v) in (K_v*/K_v*^2)^2, or None if the full image was not found."""
    d = pl.dim; target = d                               # dimension of the image: 2 or 4
    def kummer(zs):
        vs = [pl.vec(z) for z in zs]
        if any(v is None for v in vs): return None
        return vs
    rows = []
    # points of order 2
    d12, d13, d23 = gsub(e[0], e[1]), gsub(e[0], e[2]), gsub(e[1], e[2])
    v12, v13, v23 = pl.vec(d12), pl.vec(d13), pl.vec(d23)
    if None in (v12, v13, v23): return None
    rows.append(to_int(xor_vec(v12, v13) + v12))         # x = e1: ((e1-e2)(e1-e3), e1-e2)
    rows.append(to_int(v12 + xor_vec(v12, v23)))         # x = e2: (e2-e1, (e2-e1)(e2-e3)); -1 is a square
    basis = rank_basis(rows)
    p = pl.p; unif = (1, 1) if p == 2 else (p, 0)
    for t in range(tries):
        if len(basis) == target: break
        mode = t % 4
        if mode == 0:                                    # near a root
            j = rng.randint(0, 9); w = (rng.randint(-50, 50), rng.randint(-50, 50))
            x = gadd(e[rng.randint(0, 2)], gd.gmul(gpow(unif, j), w)); den = (1, 0)
        elif mode == 1:
            x = (rng.randint(-10**4, 10**4), rng.randint(-10**4, 10**4)); den = (1, 0)
        elif mode == 2:                                  # negative even valuation: x = w / unif^(2j)
            j = rng.randint(1, 4); x = (rng.randint(-200, 200), rng.randint(-200, 200)); den = gpow(unif, 2*j)
        else:
            j = rng.randint(0, 6); x = gd.gmul(gpow(unif, j), (rng.randint(-200, 200), rng.randint(-200, 200))); den = (1, 0)
        zs = [gsub(x, gd.gmul(den, ei)) for ei in e]     # (x/den - e_i) = zs_i / den, den a square
        if any(z == (0, 0) for z in zs): continue
        vs = kummer(zs)
        if vs is None: continue
        if any(xor_vec(xor_vec(vs[0], vs[1]), vs[2])): continue      # f(x) is not a square at v
        basis = rank_basis(basis + [to_int(vs[0] + vs[1])])
    return basis if len(basis) == target else None

def gauss_factor(z):
    """Gaussian primes dividing z = (a, b), as rational primes p (the places above p are all taken)."""
    N = z[0]*z[0] + z[1]*z[1]
    return set(int(q) for q in pari.factor(N)[0])

def selmer_bound(e, seed=1, verbose=False):
    """(dim Sel - 2, data) for E: y^2 = prod (x - e_i), e_i Gaussian integers; None if a local image was not found."""
    rng = random.Random(seed)
    primes = set([2])
    for i in range(3):
        for j in range(i + 1, 3):
            dz = gsub(e[i], e[j]); assert dz != (0, 0); primes |= gauss_factor(dz)
    primes = sorted(primes)
    basis = [(0, 1), (1, 1)]
    for p in primes:
        if p == 2: continue
        if p % 4 == 3: basis.append((p, 0))
        else:
            g = gd.gprime(p); basis += [g, (g[0], -g[1])]
    g = len(basis); cons = []
    for p in primes:
        for pl in places_above(p):
            img = local_image(e, pl, rng)
            if img is None: return None
            d = pl.dim; M = [pl.vec(b) for b in basis]; assert None not in M
            for phi in nullspace(img, 2*d):
                row = 0
                for k in range(g):
                    a = sum((phi >> t & 1) & M[k][t] for t in range(d)) & 1
                    c = sum((phi >> (d + t) & 1) & M[k][t] for t in range(d)) & 1
                    row |= a << k | c << (g + k)
                cons.append(row)
    dimsel = 2*g - len(rank_basis(cons))
    if verbose: print('  primes', primes, 'basis', g, 'constraints', len(cons), 'dim Sel', dimsel)
    return dimsel - 2
